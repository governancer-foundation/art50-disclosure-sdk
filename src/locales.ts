/**
 * Disclosure wording per language.
 *
 * Article 50(5) requires the information to be clear, distinguishable and
 * accessible, provided at the latest at the time of the first interaction or
 * exposure. Nothing in the Regulation prescribes a sentence, so these strings
 * are a defensible default, not a safe harbour: a deployer serving a given
 * market should have counsel read the wording it ships.
 *
 * Translations are plain and formal by design. A disclosure that reads as
 * marketing copy defeats the "clear and distinguishable" requirement.
 */

