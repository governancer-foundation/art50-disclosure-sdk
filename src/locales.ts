/** Whether a string is one of the shipped locales. */
export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

/**
 * Pick the closest shipped locale for a language tag, falling back to English.
 * "de-AT" resolves to "de"; an unshipped language resolves to "en".
 */
export function resolveLocale(tag: string | undefined): Locale {
  if (!tag) return "en";
  const primary = tag.toLowerCase().split("-")[0] ?? "";
  return isLocale(primary) ? primary : "en";
}
